function celsiusParaFahrenheit(celsius) {
    return (celsius * 9/5) + 32;
}

function quilometrosParaMetros(quilometros) {
    return quilometros * 1000;
}

function minutosParaSegundos(minutos) {
    return minutos * 60;
}

console.log(celsiusParaFahrenheit(25)); 
console.log(celsiusParaFahrenheit(70));

console.log(quilometrosParaMetros(5));
console.log(quilometrosParaMetros(20));

console.log(minutosParaSegundos(10)); 
console.log(minutosParaSegundos(50)); 